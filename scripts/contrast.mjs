// Computes WCAG 2.2 contrast ratios for every text/background pair used on the site, in both
// themes, from the values in src/styles/tokens.css, and writes docs/contrast.md.
// Exits 1 if any text pair is below 4.5:1 or any non-text pair below 3:1.
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/styles/tokens.css", import.meta.url), "utf8");
const darkStart = css.indexOf("@media (prefers-color-scheme: dark)");
const read = (block) =>
  Object.fromEntries(
    [...block.matchAll(/--(color-[\w-]+):\s*(#[0-9a-f]{6})/gi)].map((m) => [m[1], m[2]]),
  );
const light = read(css.slice(0, darkStart));
const dark = { ...light, ...read(css.slice(darkStart)) };

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = Number.parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// [foreground, background, where it is used, kind]
const PAIRS = [
  ["color-text", "color-bg", "Body text, headings", "text"],
  ["color-text-muted", "color-bg", "Lead and secondary text", "text"],
  ["color-accent-strong", "color-bg", "Links, eyebrows", "text"],
  ["color-text", "color-bg-subtle", "Text on alternate sections, footer, current nav item", "text"],
  [
    "color-text-muted",
    "color-bg-subtle",
    "Footer links, nav links on hover background, illustration meta",
    "text",
  ],
  ["color-accent-strong", "color-bg-subtle", "Eyebrows on alternate sections", "text"],
  ["color-text", "color-surface", "Cards, illustrations, secondary button", "text"],
  ["color-text-muted", "color-surface", "Card text, illustration labels and chips", "text"],
  ["color-accent-strong", "color-surface", "Links in cards", "text"],
  ["color-on-accent", "color-accent", "Primary button, solid chips", "text"],
  ["color-bg", "color-accent-strong", "Primary button on hover", "text"],
  ["color-text", "color-accent-soft", "Accent chips, access note on the guide", "text"],
  ["color-surface", "color-text", "Approve button in the Inbox illustration", "text"],
  ["color-accent-strong", "color-bg", "Focus ring against the page", "non-text"],
  ["color-accent-strong", "color-surface", "Focus ring against cards", "non-text"],
  ["color-border-strong", "color-surface", "Secondary button and chip borders", "non-text"],
  [
    "color-accent",
    "color-surface",
    "Selected marks in the decision matrix, stage markers",
    "non-text",
  ],
  ["color-accent", "color-bg", "Accent rules and the primary button shape", "non-text"],
];

const rows = [];
let failures = 0;
for (const [theme, t] of [
  ["light", light],
  ["dark", dark],
]) {
  for (const [fg, bg, use, kind] of PAIRS) {
    const r = ratio(t[fg], t[bg]);
    const min = kind === "text" ? 4.5 : 3;
    const pass = r >= min;
    if (!pass) failures++;
    rows.push(
      `| ${theme} | \`--${fg}\` ${t[fg]} | \`--${bg}\` ${t[bg]} | ${r.toFixed(2)}:1 | ${kind} (≥ ${min}:1) | ${pass ? "pass" : "FAIL"} | ${use} |`,
    );
  }
}

const doc = `# Colour contrast

Generated by \`pnpm contrast\` (scripts/contrast.mjs) from the tokens in \`src/styles/tokens.css\`.
WCAG 2.2 AA: text needs 4.5:1 or more, non-text elements such as focus rings and borders 3:1.
All text on the site is set at 13px or larger with one of the pairs below.

| Theme | Foreground | Background | Ratio | Kind | Result | Where |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

${failures ? `**${failures} pair(s) fail.**` : "Every pair passes."}
`;
writeFileSync(new URL("../docs/contrast.md", import.meta.url), doc);
console.log(doc);
process.exit(failures ? 1 : 0);
